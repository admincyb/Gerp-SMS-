							      FROM [INV_ITEM_DEPT_OPENING_STOCK_HDR]
								  WHERE [IOH_BIZUNIT]    = @V_BIZUNIT
								    AND [IOH_DEL_STATUS] = 0
								    AND [IOH_STATUS]     = 2
								    AND [IOH_DATE] < (SELECT [FYR_DATE_FROM] 
	                                                  FROM [FIN_YEAR_MST] 
	                                                  WHERE FYR_PK = @V_FIN_YEAR)
