	DECLARE	@V_DOC_HANDLE	INT,
			@V_FROM_DT		DATE,
			@V_TO_DT		DATE,
			@V_BIZUNIT		INT,
			@V_DEPT			INT,
			@V_TYPE			NVARCHAR(20),
			@V_USER			INT,
			@V_ITM_CATEGORY	INT,
			@V_ITM_PK		INT,
			@V_DPT_PK		INT,
			@V_TRAN_ONLY	TINYINT,
			@V_IS_RETURN	TINYINT,
			@V_IPD_CLASSIFICATION	NVARCHAR(200),
			@V_CUR_ROUND			TINYINT,
			@V_FIN_YEAR				INT,
